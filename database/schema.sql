-- ExploreSQL / DVD Rental schema
-- This file is the authoritative PostgreSQL DDL for the entity model.
-- Run against an empty database. It creates no sample data.

CREATE SCHEMA IF NOT EXISTS catalog;
CREATE SCHEMA IF NOT EXISTS location;
CREATE SCHEMA IF NOT EXISTS inventory;
CREATE SCHEMA IF NOT EXISTS customer;
CREATE SCHEMA IF NOT EXISTS rental;
CREATE SCHEMA IF NOT EXISTS "transaction";

DO $$
BEGIN
    CREATE TYPE public.mpaa_rating AS ENUM ('G', 'PG', 'PG-13', 'R', 'NC-17');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

CREATE OR REPLACE FUNCTION public.set_last_update()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.last_update = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

-- Location
CREATE TABLE location.country (
    country_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country varchar(50) NOT NULL,
    last_update timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE location.city (
    city_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city varchar(50),
    country_id integer NOT NULL REFERENCES location.country(country_id),
    last_update timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE location.address (
    address_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address varchar(50),
    address2 varchar(50),
    district varchar(20),
    city_id integer NOT NULL REFERENCES location.city(city_id),
    postal_code varchar(10),
    phone varchar(20) NOT NULL,
    last_update timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Catalogue
CREATE TABLE catalog.actor (
    actor_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(45) NOT NULL,
    last_name varchar(45) NOT NULL,
    last_update timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE catalog.category (
    category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(25) NOT NULL,
    last_update timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE catalog.language (
    language_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(20) NOT NULL,
    last_update timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE catalog.film (
    film_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    description text,
    release_year integer,
    language_id integer NOT NULL REFERENCES catalog.language(language_id),
    rental_duration smallint NOT NULL,
    rental_rate numeric(4,2) NOT NULL,
    length smallint NOT NULL,
    replacement_cost numeric(5,2) NOT NULL,
    rating public.mpaa_rating,
    last_update timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    special_features text[],
    fulltext tsvector NOT NULL
);

CREATE TABLE catalog.film_actor (
    actor_id integer NOT NULL REFERENCES catalog.actor(actor_id),
    film_id integer NOT NULL REFERENCES catalog.film(film_id),
    last_update timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (actor_id, film_id)
);

CREATE TABLE catalog.film_category (
    film_id integer NOT NULL REFERENCES catalog.film(film_id),
    category_id integer NOT NULL REFERENCES catalog.category(category_id),
    last_update timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (film_id, category_id)
);

-- Store and staff are created before their circular foreign keys are added.
CREATE TABLE inventory.store (
    store_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manager_staff_id integer NOT NULL,
    address_id integer NOT NULL REFERENCES location.address(address_id),
    last_update timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_store_manager UNIQUE (manager_staff_id)
);

CREATE TABLE inventory.staff (
    staff_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(45) NOT NULL,
    last_name varchar(45) NOT NULL,
    address_id integer NOT NULL REFERENCES location.address(address_id),
    email varchar(50),
    store_id integer NOT NULL,
    active boolean NOT NULL,
    username varchar(16) NOT NULL,
    password varchar(40),
    last_update timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    picture bytea
);

ALTER TABLE inventory.store
    ADD CONSTRAINT fk_store_manager
    FOREIGN KEY (manager_staff_id) REFERENCES inventory.staff(staff_id)
    DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE inventory.staff
    ADD CONSTRAINT fk_staff_store
    FOREIGN KEY (store_id) REFERENCES inventory.store(store_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE inventory.inventory (
    inventory_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    film_id integer NOT NULL REFERENCES catalog.film(film_id),
    store_id integer NOT NULL REFERENCES inventory.store(store_id),
    last_update timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Customers, rentals, and payments
CREATE TABLE customer.customer (
    customer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id integer NOT NULL REFERENCES inventory.store(store_id),
    first_name varchar(45) NOT NULL,
    last_name varchar(45) NOT NULL,
    email varchar(50),
    address_id integer NOT NULL REFERENCES location.address(address_id),
    activebool boolean NOT NULL DEFAULT TRUE,
    create_date date NOT NULL DEFAULT CURRENT_DATE,
    last_update timestamptz DEFAULT CURRENT_TIMESTAMP,
    active integer
);

CREATE TABLE rental.rental (
    rental_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_date timestamptz NOT NULL,
    inventory_id integer NOT NULL REFERENCES inventory.inventory(inventory_id),
    customer_id integer NOT NULL REFERENCES customer.customer(customer_id),
    return_date timestamptz,
    staff_id integer NOT NULL REFERENCES inventory.staff(staff_id),
    last_update timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rental_event UNIQUE (rental_date, inventory_id, customer_id)
);

CREATE TABLE "transaction".payment (
    payment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES customer.customer(customer_id),
    staff_id integer NOT NULL REFERENCES inventory.staff(staff_id),
    rental_id integer NOT NULL REFERENCES rental.rental(rental_id),
    amount numeric(5,2) NOT NULL,
    payment_date timestamptz NOT NULL
);

-- Indexes for joins and common lookups.
CREATE INDEX idx_city_country_id ON location.city(country_id);
CREATE INDEX idx_address_city_id ON location.address(city_id);
CREATE INDEX idx_film_language_id ON catalog.film(language_id);
CREATE INDEX idx_film_actor_film_id ON catalog.film_actor(film_id);
CREATE INDEX idx_film_category_category_id ON catalog.film_category(category_id);
CREATE INDEX idx_staff_address_id ON inventory.staff(address_id);
CREATE INDEX idx_inventory_film_id ON inventory.inventory(film_id);
CREATE INDEX idx_inventory_store_id ON inventory.inventory(store_id);
CREATE INDEX idx_customer_store_id ON customer.customer(store_id);
CREATE INDEX idx_customer_address_id ON customer.customer(address_id);
CREATE INDEX idx_customer_last_name ON customer.customer(last_name);
CREATE INDEX idx_rental_inventory_id ON rental.rental(inventory_id);
CREATE INDEX idx_rental_customer_id ON rental.rental(customer_id);
CREATE INDEX idx_rental_staff_id ON rental.rental(staff_id);
CREATE INDEX idx_payment_customer_id ON "transaction".payment(customer_id);
CREATE INDEX idx_payment_staff_id ON "transaction".payment(staff_id);
CREATE INDEX idx_payment_rental_id ON "transaction".payment(rental_id);
CREATE INDEX idx_film_fulltext ON catalog.film USING gin(fulltext);

